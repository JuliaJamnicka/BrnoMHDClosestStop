# Writes the lettered page titles as Android vector drawables (light and night, English and Czech).
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from letters import G, ACCENT, GAP

def vector(text, blue, red):
    x, groups, reds = 0.0, [], []
    for ch in text:
        base, cx = ACCENT[ch] if ch in ACCENT else (ch, None)
        paths, dots, w = G[base]
        body = ''.join(
            f'\n        <path android:pathData="{p}" android:strokeColor="{blue}" android:strokeWidth="24"'
            f' android:strokeLineCap="round" android:strokeLineJoin="round" />' for p in paths)
        body += ''.join(
            f'\n        <path android:pathData="M{dx - 14},{dy}a14,14 0,1 0,28 0a14,14 0,1 0,-28 0z" android:fillColor="{blue}" />'
            for dx, dy in dots)
        groups.append(f'    <group android:translateX="{x + 20:.1f}" android:translateY="-10">{body}\n    </group>')
        if cx is not None:
            reds.append(f'    <path android:pathData="M{x + 20 + cx - 10:.1f},52L{x + 20 + cx + 12:.1f},30" android:strokeColor="{red}"'
                        f' android:strokeWidth="22" android:strokeLineCap="round" />')
        x += w + GAP
    width = x - GAP + 40
    # same scale as the wordmark (ic_wordmark: 195 units = 48dp)
    return (f'<?xml version="1.0" encoding="utf-8"?>\n<!-- "{text}", lettered like the wordmark (generated by docs/brand/lettering/android.py) -->\n'
            f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            f'    android:width="{width * 48 / 195:.1f}dp" android:height="{280 * 48 / 195:.1f}dp"\n'
            f'    android:viewportWidth="{width:.0f}" android:viewportHeight="280">\n'
            + '\n'.join(groups + reds) + '\n</vector>\n')

TITLES = {'title_stops': {'': 'Stops', 'cs': 'Zastávky'}, 'title_radar': {'': 'Radar'}, 'title_settings': {'': 'Settings', 'cs': 'Nastavení'}}
COLOURS = {'': ('#1A4FA3', '#E3242B'), 'night': ('#FFFFFF', '#F0373E')}
res = sys.argv[1]
for name, langs in TITLES.items():
    for lang, text in langs.items():
        for theme, (blue, red) in COLOURS.items():
            folder = 'drawable' + ''.join('-' + q for q in (lang, theme) if q)
            os.makedirs(os.path.join(res, folder), exist_ok=True)
            open(os.path.join(res, folder, name + '.xml'), 'w', encoding='utf-8').write(vector(text, blue, red))
            print(folder, name, text)
